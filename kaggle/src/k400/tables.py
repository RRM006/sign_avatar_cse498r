"""Write one table three ways for the paper: CSV (data), Markdown (reading), LaTeX booktabs (paper)."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from bdsl.io import atomic_write_text

_LATEX_ESC = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
              "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "\\": r"\textbackslash{}"}


def _esc(x) -> str:
    return "".join(_LATEX_ESC.get(c, c) for c in str(x))


def to_markdown(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for row in df.astype(str).itertuples(index=False):
        lines.append("| " + " | ".join(v.replace("|", "/") for v in row) + " |")
    return "\n".join(lines) + "\n"


def to_latex(df: pd.DataFrame, caption: str, label: str) -> str:
    cols = list(df.columns)
    spec = "l" + "r" * (len(cols) - 1)
    body = "\n".join(" & ".join(_esc(v) for v in row) + r" \\" for row in df.astype(str).itertuples(index=False))
    return (f"% generated by kaggle/src/k400/report.py — do not edit by hand\n"
            f"\\begin{{table}}[t]\n\\centering\n\\small\n\\caption{{{_esc(caption)}}}\n\\label{{{label}}}\n"
            f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n" + " & ".join(_esc(c) for c in cols) + r" \\" + "\n\\midrule\n"
            + body + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")


def write_table(df: pd.DataFrame, out_dir: Path, name: str, caption: str, note: str = "") -> dict:
    out_dir.mkdir(parents=True, exist_ok=True)
    atomic_write_text(out_dir / f"{name}.csv", "\ufeff" + df.to_csv(index=False, lineterminator="\n"))
    md = f"### {caption}\n\n" + to_markdown(df) + (f"\n{note}\n" if note else "")
    atomic_write_text(out_dir / f"{name}.md", md)
    atomic_write_text(out_dir / f"{name}.tex", to_latex(df, caption + (f" {note}" if note else ""), f"tab:{name}"))
    return {"name": name, "rows": len(df), "files": [f"{name}.csv", f"{name}.md", f"{name}.tex"]}


def fmt(x, nd: int = 3) -> str:
    try:
        if x is None or pd.isna(x):
            return "n/a"
    except (TypeError, ValueError):
        pass
    return f"{float(x):.{nd}f}"


def fmt_ci(ci: dict | None, nd: int = 3) -> str:
    if not ci:
        return "n/a"
    return f"[{fmt(ci.get('low'), nd)}, {fmt(ci.get('high'), nd)}]"

def _csv_text(df: pd.DataFrame) -> str:
    return df.to_csv(index=False, lineterminator="\n")


def cmd_manifest(args) -> int:
    from .data.manifest import build_manifest

    cfg = load_config(env=args.env, data=args.data)
    df, meta = build_manifest(cfg, workers=args.workers)
    print(json.dumps({k: meta[k] for k in ("csv", "csv_sha256", "sources_unchanged", "timing_seconds")}, indent=2))
    print(json.dumps(meta["counts"], indent=2, ensure_ascii=False))
    return 0


def _split_paths(cfg):
    s = cfg["split"]
    base = ensure_dir(cfg_path(cfg, "splits_dir")) / f"{s['name']}_{s['version']}"
    return base.with_suffix(".csv"), base.with_suffix(".meta.json")


def cmd_split(args) -> int:
    from .data.manifest import load_manifest
    from .data.split import assign_split, balance_report, verify_no_leakage

    cfg = load_config(env=args.env, data="full")
    s = cfg["split"]
    manifest = load_manifest(cfg)
    split_df = assign_split(manifest, s["salt"], s["ratios"])
    links = s.get("known_shared_segment_links")
    problems = verify_no_leakage(split_df, links)
    csv_path, meta_path = _split_paths(cfg)
    atomic_write_text(csv_path, _csv_text(split_df[["index", "group_id", "split"]]))
    meta = {
        "split": f"{s['name']}_{s['version']}", "generated_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "salt": s["salt"], "ratios": s["ratios"], "known_shared_segment_links": links,
        "csv": csv_path.name, "csv_sha256": sha256_file(csv_path),
        "manifest_csv_sha256": sha256_file(cfg_path(cfg, "manifests_dir") / f"manifest_{cfg['manifest']['version']}.csv"),
        "config_hash": cfg["_meta"]["config_hash"],
        "leakage_problems": problems,
        "balance": balance_report(manifest, split_df, cfg["pilot"]["low_res_short_side"]),
    }
    atomic_write_json(meta_path, meta)
    print(json.dumps({k: meta[k] for k in ("split", "csv_sha256", "leakage_problems")}, indent=2))
    print(json.dumps(meta["balance"], indent=1, ensure_ascii=False))
    return 1 if problems else 0


def _selection_paths(cfg):
    base = ensure_dir(cfg_path(cfg, "pilot_work_dir")) / f"{cfg['pilot']['name']}_selection"
    return base.with_suffix(".csv"), base.with_suffix(".meta.json")


def cmd_pilot_select(args) -> int:
    from .data.manifest import load_manifest
    from .data.pilot import select_pilot

    cfg = load_config(env=args.env, data="full")
    manifest = load_manifest(cfg)
    split_csv, _ = _split_paths(cfg)
    split_df = pd.read_csv(split_csv)
    sel, report = select_pilot(manifest, split_df, cfg["pilot"])
    csv_path, meta_path = _selection_paths(cfg)
    atomic_write_text(csv_path, _csv_text(sel))
    meta = {"pilot": cfg["pilot"]["name"], "generated_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "csv": csv_path.name, "csv_sha256": sha256_file(csv_path), "split_csv_sha256": sha256_file(split_csv),
            "config_hash": cfg["_meta"]["config_hash"], "pilot_config": cfg["pilot"], "report": report}
    atomic_write_json(meta_path, meta)
    print(json.dumps({k: v for k, v in report.items() if k != "strata"}, indent=1, ensure_ascii=False))
    return 0 if report["ok"] else 1


def _protocol_md(cfg: dict, sel_meta: dict, split_meta: dict, copy_ok: int) -> str:
    p, r = cfg["pilot"], sel_meta["report"]
    fams = "\n".join(f"  - F{n}: `{k}`" for n, k in enumerate(r["families"], 1))
    return f"""# {p['name']} — selection protocol

Generated by `uv run python -m bdsl.cli pilot-select` (code: `src/bdsl/data/pilot.py`); copied by
`pilot-copy` after the owner approved the list. Design: `research/design_proposals/04_…` §F-6;
ADR-0017 (copies), ADR-0018 (split). **Pilot results are "pipeline tests", never generalisation.**

## Inputs (hashes)
- Manifest: `{split_meta['manifest_csv_sha256']}` (SHA-256 of `work/manifests/manifest_{cfg['manifest']['version']}.csv`)
- Split {split_meta['split']}: `{split_meta['csv_sha256']}` (salt `{split_meta['salt']}`, ratios {split_meta['ratios']})
- Selection list: `{sel_meta['csv_sha256']}`
- Config hash: `{sel_meta['config_hash']}`; seed `{p['seed']}`

## Rules
1. Pool: one clip per normalised sentence (`norm_v1`), representative (no exact copies), decodable,
   no label conflict, assigned to train/val/test in {split_meta['split']} ({r['pool_size']} clips).
2. Core ({p['core']['families']} minimal-pair families, i.e. same length and exactly one word different):
   per family {p['core']['train_per_family']} train clips + 1 held-out sibling (half of the families give val,
   half test; families with siblings in only one split choose first). Rule 4 may swap that sibling.
3. Diversity (indicative word lists in `src/bdsl/text/tags.py`, not linguistic labels):
   train {p['diversity_train']}; held-out {p['diversity_heldout']}.
4. Held-out clips are chosen after all train clips. Prefer in-vocabulary held-out: {p.get('heldout_prefer_in_vocab')}
   (a sentence whose words all occur in pilot train, i.e. a new combination of seen words); where none
   exists, the unseen words are listed (`unseen_in_pilot_train`). Non-sibling fallback for core slots:
   {p.get('heldout_fallback_pool')}. Result: {r['heldout_all_words_seen']}/{r['heldout_total']} held-out clips use only seen words.
5. Quotas: {p['quotas']} (low-res = short side < {p['low_res_short_side']} px). Candidates that fill an
   unmet quota are preferred; unmet quotas fail the selection.
6. Every choice is an ordering by SHA-256 of (seed, …): re-running gives the same 50 clips.

## Result
- Counts: {r['counts']}; landscape {r['landscape']}, low-res {r['low_res']}, hard share {r['hard_share']};
  duration quartiles {r['duration_quartiles']}; quotas unmet: {r['quotas_unmet'] or 'none'}.
- Families:
{fams}
- Copies verified by SHA-256: {copy_ok}/{sum(r['counts'].values())}.

## Known limitations
- Hand-picked strata rely on word lists; a "question" or "negation" tag is only likely.
- Timestamp irregularity is not yet measured (Day 2), so it was not used as a quota.
- Signer identity is unknown (ADR-0018): pilot clips may share signers across splits.
- Split {split_meta['split']} is provisional until the full shared-segment scan (open_questions G2).
"""


def _readme_md(cfg: dict) -> str:
    return f"""# {cfg['pilot']['name']}

The 50-video pilot set for the 5-day prototype (milestone 6). Selected from split S1 by
`bdsl.cli pilot-select`; see `SELECTION_PROTOCOL.md` for the rules and input hashes.

- `videos/` — byte-identical **copies** of `initial_dataset/SIGN_LANGUAGE_DATA/<Index>.mp4`
  (gitignored; ADR-0017). The originals are never moved or changed.
- `pilot50_manifest.csv` — one row per clip: Index, split, selection reason, sentence, metadata and
  the SHA-256 checked after copying.

This is **not** the committed 50-clip sample in `initial_dataset/videos/` (`sample50`).
Results on this pilot are "pipeline tests", not evidence of generalisation.
"""


def cmd_pilot_copy(args) -> int:
    from .data.pilot import copy_pilot

    if not args.confirm:
        print("Refusing to copy without --confirm (the owner must approve the 50-clip list first).")
        return 2
    cfg = load_config(env=args.env, data="pilot50")
    csv_path, meta_path = _selection_paths(cfg)
    sel_meta = json.loads(meta_path.read_text(encoding="utf-8"))
    if sha256_file(csv_path) != sel_meta["csv_sha256"]:
        print("Selection CSV changed since it was generated; re-run pilot-select and get approval again.")
        return 1
    split_meta = json.loads(_split_paths(cfg)[1].read_text(encoding="utf-8"))
    sel = pd.read_csv(csv_path, dtype={"sha256": str})
    dest = Path(cfg["paths"]["pilot_dest_dir"])
    results = copy_pilot(sel, Path(cfg["paths"]["data_root"]), Path(cfg["data"]["video_root"]))
    res = pd.DataFrame(results)
    out = sel.merge(res[["index", "sha256_ok"]], on="index")
    atomic_write_text(dest / "pilot50_manifest.csv", _csv_text(out))
    ok = int(res["sha256_ok"].sum())
    atomic_write_text(dest / "SELECTION_PROTOCOL.md", _protocol_md(cfg, sel_meta, split_meta, ok))
    atomic_write_text(dest / "README.md", _readme_md(cfg))
    print(json.dumps({"copied": int(res["copied"].sum()), "already_present": int((~res["copied"]).sum()),
                      "sha256_ok": ok, "total": len(res)}, indent=2))
    return 0 if ok == len(res) else 1


def cmd_extract(args) -> int:
    from .features.extract import run_extraction
    from .features.layout import privacy_problems
    from .features.qc import compare_modes, write_qc

    if args.data != "pilot50":
        print("Only --data pilot50 is authorised so far (full-set extraction needs the owner's go).")
        return 2
    cfg = load_config(env=args.env, data=args.data)
    manifest = pd.read_csv(Path(cfg["paths"]["pilot_dest_dir"]) / "pilot50_manifest.csv", dtype={"sha256": str})
    video_root = Path(cfg["data"]["video_root"])
    clips = [(int(i), video_root / f"{int(i)}.mp4") for i in manifest["index"]]

    def copies_ok() -> list[int]:
        return [int(i) for i, h in zip(manifest["index"], manifest["sha256"]) if sha256_file(video_root / f"{int(i)}.mp4") != h]

    bad_before = copies_ok()
    if bad_before:
        print(f"Pilot copies differ from pilot50_manifest.csv: {bad_before}")
        return 1
    out_root = Path(args.out_root) if args.out_root else Path(cfg["paths"]["features_dir"])
    modes = ["video", "image"] if args.mode == "both" else [args.mode]
    qc_by_mode, status = {}, 0
    for mode in modes:
        run = run_extraction(cfg, clips, mode, out_root=out_root, workers=args.workers)
        out_dir = run["out_dir"]
        qc = write_qc(out_dir, [i for i, _ in clips], run["failures"])
        privacy = {i: p for i, _ in clips if (out_dir / f"{i}.npz").exists() for p in [privacy_problems(out_dir / f"{i}.npz")] if p}
        summary = {**{k: v for k, v in run.items() if k != "out_dir"}, "clips_with_features": int(len(qc)),
                   "privacy_problems": privacy}
        atomic_write_json(out_dir / "extract_run.json", summary)
        qc_by_mode[mode] = qc
        print(json.dumps({k: summary[k] for k in ("mode", "feat_ver", "extracted_this_run", "clips_with_features",
                                                   "seconds")} | {"failures": len(run["failures"]),
                                                                  "privacy_problems": len(privacy)}))
        if run["failures"] or privacy or len(qc) != len(clips):
            status = 1
    if len(qc_by_mode) > 1:
        comparison = compare_modes(qc_by_mode)
        atomic_write_json(out_root / "compare_pilot50.json", comparison)
        print(json.dumps(comparison, indent=1))
    bad_after = copies_ok()
    print(f"pilot copies unchanged: {not bad_after}")
    return 1 if bad_after else status


def _annotation_paths(cfg):
    d = Path(cfg["paths"]["annotations_dir"])
    a = cfg["annotations"]
    return d / a["pilot_file"], d / a["reviewers_file"]


def cmd_gloss_draft(args) -> int:
    from .data.manifest import read_sheet
    from .text.annotations import any_reviewed, build_drafts, read_csv, validate, write_csv
    from .text.normalize import tokens

    if args.data != "pilot50":
        print("Only --data pilot50 is authorised so far.")
        return 2
    cfg = load_config(env=args.env, data=args.data)
    out, reviewers_path = _annotation_paths(cfg)
    if out.exists() and any_reviewed(read_csv(out)):
        print(f"Refusing to overwrite {out.name}: it contains human-reviewed rows.")
        return 2
    pilot = pd.read_csv(Path(cfg["paths"]["pilot_dest_dir"]) / "pilot50_manifest.csv", dtype={"sentence_raw": str})
    corpus = {t for s in read_sheet(cfg)["sentence_raw"] for t in tokens(s)}
    drafts, rule_counts = build_drafts(pilot, corpus, cfg["annotations"]["g0_ver"])
    write_csv(drafts, out)
    problems = validate(read_csv(out), read_csv(reviewers_path), set(pilot["index"].astype(int)))
    print(json.dumps({"file": out.name, "rows": len(drafts), "status": drafts["status"].value_counts().to_dict(),
                      "tokens_per_rule": rule_counts, "sha256": sha256_file(out), "validation_problems": problems},
                     indent=1, ensure_ascii=False))
    return 1 if problems else 0


TEST_DATA_WARNING = ("TEST RUN: --allow-test-data accepts mock / not-video-verified rows. "
                     "Nothing produced with it is a real result.")


def check_annotations(cfg, allow_test_data: bool = False) -> dict:
    """Validate the pilot annotation file; training code must refuse to start unless `problems` is empty."""
    from .text.annotations import is_test_data, read_csv, usable_for_training, validate

    path, reviewers_path = _annotation_paths(cfg)
    df = read_csv(path)
    pilot = pd.read_csv(Path(cfg["paths"]["pilot_dest_dir"]) / "pilot50_manifest.csv")
    problems = validate(df, read_csv(reviewers_path), set(pilot["index"].astype(int)), allow_test_data)
    report = {"file": path.name, "file_sha256": sha256_file(path), "rows": len(df),
              "status": df["status"].value_counts().to_dict(), "test_data_rows": int(is_test_data(df).sum()),
              "usable_for_training": len(usable_for_training(df, allow_test_data)), "problems": problems}
    if allow_test_data:
        report = {"TEST_RUN": True, "warning": TEST_DATA_WARNING, **report}
    return report


def cmd_gloss_validate(args) -> int:
    cfg = load_config(env=args.env, data="pilot50")
    report = check_annotations(cfg, args.allow_test_data)
    print(json.dumps(report, indent=1, ensure_ascii=False))
    return 1 if report["problems"] else 0


def cmd_train_text2gloss(args) -> int:
    from .models.train_text2gloss import ResumeMismatch, run
    from .text.annotations import read_csv, usable_for_training

    if args.data != "pilot50":
        print("Only --data pilot50 is authorised so far.")
        return 2
    cfg = load_config(env=args.env, data=args.data)
    # Guard: no training unless the annotation check is clean (ADR-0024).
    check = check_annotations(cfg, args.allow_test_data)
    if check["problems"]:
        print(json.dumps(check, indent=1, ensure_ascii=False))
        print("Refusing to train: gloss-validate reports problems.")
        return 2
    if args.allow_test_data:
        print(TEST_DATA_WARNING)
    path, _ = _annotation_paths(cfg)
    df = usable_for_training(read_csv(path), args.allow_test_data)
    manifest_path = Path(cfg["paths"]["pilot_dest_dir"]) / "pilot50_manifest.csv"
    pilot = pd.read_csv(manifest_path, dtype={"index": str})
    split_of = dict(zip(pilot["index"], pilot["split"]))
    moved = [i for i, s in zip(df["index"], df["split"]) if split_of.get(i) != s]
    if moved:
        print(f"Refusing to train: split differs from pilot50_manifest.csv for rows {moved}.")
        return 2
    try:
        result = run(cfg, df, check, allow_test_data=args.allow_test_data,
                     pilot_manifest_sha256=sha256_file(manifest_path),
                     run_dir=Path(args.resume) if args.resume else None, runs_root=cfg_path(cfg, "runs_dir"),
                     seeds=args.seeds, overfit=args.overfit, stop_after=args.stop_after_epochs)
    except ResumeMismatch as e:
        print(f"Refusing to resume: {e}")
        return 2
    if sha256_file(path) != check["file_sha256"]:
        print(f"{path.name} changed during training: discard run {result['run_dir']}.")
        return 1
    print(json.dumps({"run_dir": result["run_dir"], "finished": result["finished"]}, indent=1))
    return 0


MODEL_B_INPUT_COLUMNS = ["index", "split", "sentence_raw", "sentence_norm", "norm_ver", "g0_ver", "gloss_auto",
                         "tags_auto"]


def check_model_b_inputs(cfg) -> tuple[pd.DataFrame, list[str], str]:
    """Model B reads only the G0 columns of the annotation file (never the reviewed ones). Checks them,
    the split and the feature files; returns (inputs, problems, SHA-256 of the inputs)."""
    from .features.layout import read_meta
    from .text.annotations import read_csv
    from .text.normalize import NORM_VER, normalize

    path, _ = _annotation_paths(cfg)
    df = read_csv(path)[MODEL_B_INPUT_COLUMNS]
    pilot = pd.read_csv(Path(cfg["paths"]["pilot_dest_dir"]) / "pilot50_manifest.csv", dtype={"index": str})
    split_of = dict(zip(pilot["index"], pilot["split"]))
    features_dir = Path(cfg["paths"]["features_dir"]) / cfg["gloss2motion"]["feat_ver"]
    problems = []
    if sorted(df["index"]) != sorted(split_of):
        problems.append("annotation rows do not match the pilot manifest")
    for r in df.to_dict("records"):
        if r["split"] != split_of.get(r["index"]):
            problems.append(f"row {r['index']}: split differs from pilot50_manifest.csv")
        if r["g0_ver"] != cfg["annotations"]["g0_ver"]:
            problems.append(f"row {r['index']}: g0_ver {r['g0_ver']!r} is not {cfg['annotations']['g0_ver']!r}")
        if r["sentence_norm"] != normalize(r["sentence_raw"]) or r["norm_ver"] != NORM_VER:
            problems.append(f"row {r['index']}: sentence_norm does not match {NORM_VER}")
        meta = read_meta(features_dir / f"{r['index']}.npz")
        if not meta or meta.get("feat_ver") != cfg["gloss2motion"]["feat_ver"]:
            problems.append(f"row {r['index']}: no features with feat_ver {cfg['gloss2motion']['feat_ver']}")
    inputs_sha = hashlib.sha256(_csv_text(df.sort_values("index")).encode("utf-8")).hexdigest()
    return df, problems, inputs_sha


def cmd_train_gloss2motion(args) -> int:
    from .models.train_gloss2motion import ResumeMismatch, run

    if args.data != "pilot50":
        print("Only --data pilot50 is authorised so far.")
        return 2
    cfg = load_config(env=args.env, data=args.data)
    df, problems, inputs_sha = check_model_b_inputs(cfg)
    if problems:
        print(json.dumps({"problems": problems}, indent=1, ensure_ascii=False))
        print("Refusing to train: Model B inputs failed the checks.")
        return 2
    manifest_path = Path(cfg["paths"]["pilot_dest_dir"]) / "pilot50_manifest.csv"
    try:
        result = run(cfg, df, mode=args.input, features_dir=Path(cfg["paths"]["features_dir"]) / cfg["gloss2motion"]["feat_ver"],
                     pilot_manifest_sha256=sha256_file(manifest_path), inputs_sha256=inputs_sha,
                     run_dir=Path(args.resume) if args.resume else None, runs_root=cfg_path(cfg, "runs_dir"),
                     seeds=args.seeds, overfit=args.overfit, stop_after=args.stop_after_epochs)
    except ResumeMismatch as e:
        print(f"Refusing to resume: {e}")
        return 2
    print(json.dumps({"run_dir": result["run_dir"], "finished": result["finished"]}, indent=1))
    return 0


